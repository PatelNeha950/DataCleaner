# =========================================================
# DATA QUALITY SCORE
# =========================================================

def generate_data_quality_score(df: pd.DataFrame) -> int:
    """
    Calculate a simple data quality score.
    """
    try:
        rows = len(df)
        cols = len(df.columns)
        missing = int(df.isnull().sum().sum())
        duplicates = int(df.duplicated().sum())

        total_cells = rows * cols
        if total_cells == 0:
            return 0

        missing_ratio = missing / total_cells
        duplicate_ratio = duplicates / max(rows, 1)

        score = 100
        score -= missing_ratio * 60
        score -= duplicate_ratio * 40

        return max(0, min(100, round(score)))

    except Exception:
        return 0


# =========================================================
# QUALITY BADGE
# =========================================================

def get_quality_badge(score: int) -> str:
    if score >= 90:
        return "🟢 Excellent"
    elif score >= 75:
        return "🟡 Good"
    elif score >= 50:
        return "🟠 Fair"
    return "🔴 Poor"
