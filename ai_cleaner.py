import time
import pandas as pd
from google import genai
from google.genai import errors

from config import GOOGLE_API_KEY, MODEL_NAME


# =========================================================
# GEMINI CLIENT & RETRY ENGINE
# =========================================================

def get_client():
    if not GOOGLE_API_KEY:
        raise ValueError(
            "GOOGLE_API_KEY is not configured. "
            "Please add GOOGLE_API_KEY in Streamlit Cloud Secrets "
            "or your local .env file."
        )
    return genai.Client(api_key=GOOGLE_API_KEY)


def call_gemini_with_retry(prompt: str, max_retries: int = 3, initial_delay: float = 3.0) -> str:
    """
    Executes a Gemini API call with exponential backoff retry on 429 Rate Limit errors.
    """
    delay = initial_delay

    for attempt in range(max_retries):
        try:
            client = get_client()
            response = client.models.generate_content(
                model=MODEL_NAME,
                contents=prompt
            )

            if hasattr(response, "text") and response.text:
                return response.text

            return "⚠️ No response text was generated by Gemini."

        except errors.APIError as e:
            # Check for 429 status code or Resource Exhausted messages
            is_429 = getattr(e, 'code', None) == 429 or "429" in str(e) or "RESOURCE_EXHAUSTED" in str(e)

            if is_429 and attempt < max_retries - 1:
                time.sleep(delay)
                delay *= 2  # Double delay for next attempt (3s -> 6s -> 12s)
                continue
            elif is_429:
                return (
                    "### ⏳ Quota Limit Reached (429)\n\n"
                    "The Gemini API rate limit or daily free tier quota has been exceeded.\n\n"
                    "**Quick Solutions:**\n"
                    "1. **Wait 10–15 seconds** and try again.\n"
                    "2. Change `MODEL_NAME` in `config.py` to `gemini-2.5-flash` or `gemini-2.0-flash`.\n"
                    "3. Add a billing account to your Google AI Studio project for higher quota limits."
                )
            else:
                return f"### ❌ Gemini API Error\n\n```\n{str(e)}\n```"

        except Exception as e:
            return f"### ❌ Unexpected Error\n\n```\n{str(e)}\n```"


